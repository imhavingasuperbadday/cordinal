// Read and rewrite a file's bytes by range, without loading it whole. FileSource is the read side
// (a shared handle that pins the ranges other writers must not change); FileRewrite is the write
// side, building a sibling temp file that replaces the original only on Commit.
#pragma once
#include <windows.h>
#include <cstdint>
#include <memory>
#include <string>
#include <string_view>

// Read only the metadata a format needs. Audio is copied as file ranges, never materialized
// as a song-sized string. The open source prevents other writers from changing those ranges.
class FileSource {
public:
    explicit FileSource(const std::wstring& path);
    ~FileSource() { Close(); }
    FileSource(const FileSource&) = delete;
    FileSource& operator=(const FileSource&) = delete;
    bool Valid() const { return handle_ != INVALID_HANDLE_VALUE; }
    uint64_t Size() const { return size_; }
    bool Read(uint64_t offset, size_t bytes, std::string& out);
    bool Read(uint64_t offset, size_t bytes, char* out);
    void Close();

private:
    HANDLE handle_ = INVALID_HANDLE_VALUE;
    uint64_t size_ = 0;
};

// An edit recipe: generated bytes interleaved with unchanged source ranges. Writes a sibling
// temp file with a single 64 KiB copy buffer, then atomically replaces the original on Commit.
// Destruction without Commit (including parse/write failures) removes the temp file.
class FileRewrite {
public:
    FileRewrite(const std::wstring& path, FileSource& source, std::wstring& error);
    ~FileRewrite();
    FileRewrite(const FileRewrite&) = delete;
    FileRewrite& operator=(const FileRewrite&) = delete;
    bool Write(std::string_view bytes);
    bool Copy(uint64_t offset, uint64_t bytes);
    bool Zeros(uint64_t bytes);
    bool Commit();

private:
    std::wstring path_, temp_;
    FileSource& source_;
    std::wstring& error_;
    HANDLE handle_ = INVALID_HANDLE_VALUE;
    std::unique_ptr<char[]> buffer_;
    bool ok_ = false;
};
