#!/usr/bin/env python3
"""The page side of linux/code-profile.sh, and the linker script it writes.

  code-profile.py pages PID PROGRAM OUT
                      append to OUT the page numbers of PROGRAM's code that process PID has resident
  code-profile.py write PROGRAM PAGES SCRIPT
                      write SCRIPT (linux/hot-code.ld): every function on those pages

The player started with CORDINAL_CODE_PROFILE maps each page of its code on its own (memory.cpp,
PrepareCodeProfile), so the kernel maps no page it didn't run, and its first trim lets go of startup's:
the code pages resident after that are the ones it ran.
"""
import mmap
import re
import subprocess
import sys

PAGE = mmap.PAGESIZE


def resident(pid, program):
    pages = []
    current = None
    with open(f"/proc/{pid}/smaps") as f:
        for line in f:
            head = re.match(r"([0-9a-f]+)-([0-9a-f]+) (\S+) ([0-9a-f]+) \S+ \d+\s*(.*)$", line)
            if head:
                start, end, perms, offset, path = head.groups()
                current = None
                if path.strip() == program and "x" in perms:
                    current = (int(offset, 16) // PAGE, (int(end, 16) - int(start, 16)) // PAGE)
            elif current and line.startswith("Rss:") and int(line.split()[1]) > 0:
                first, count = current
                if count == 1:
                    pages.append(first)
                else:  # a mapping the profile didn't split: count its every page
                    pages.extend(range(first, first + count))
    return pages


def loads(program):
    """(vaddr, offset, filesz) of each loadable segment that executes."""
    out = []
    for line in subprocess.run(["readelf", "-lW", program], capture_output=True, text=True, check=True).stdout.splitlines():
        f = line.split()
        if len(f) >= 8 and f[0] == "LOAD" and "E" in "".join(f[6:-1]):
            out.append((int(f[2], 16), int(f[1], 16), int(f[4], 16)))
    return out


def write(program, pages_file, script):
    pages = set()
    with open(pages_file) as f:
        for line in f:
            if line.strip():
                pages.add(int(line))
    segments = loads(program)
    hot = []
    seen = set()
    listing = subprocess.run(["nm", "-S", "--defined-only", "-n", program], capture_output=True, text=True,
                             check=True).stdout
    for line in listing.splitlines():
        f = line.split()
        if len(f) != 4 or f[2] not in "tTwW":
            continue
        addr, size, name = int(f[0], 16), int(f[1], 16), f[3]
        offset = None
        for vaddr, off, filesz in segments:
            if vaddr <= addr < vaddr + filesz:
                offset = addr - vaddr + off
        if offset is None or size == 0:
            continue
        if not any(p in pages for p in range(offset // PAGE, (offset + size - 1) // PAGE + 1)):
            continue
        # -ffunction-sections names a function's section after it. A split-off cold part that ran
        # counts for its function; the part itself stays in .text.unlikely with the other cold code.
        base = name[:-5] if name.endswith(".cold") else name
        if not re.fullmatch(r"[A-Za-z0-9_.$]+", base) or base in seen:
            continue
        seen.add(base)
        hot.append(base)
    with open(script, "w", newline="\n") as out:
        out.write("/* The functions the Linux player runs while it plays and sits idle, linked together so the\n"
                  "   pages it keeps are mostly code it uses (docs/memory.md, \"Linux code layout\").\n"
                  "   Generated by linux/code-profile.sh; refresh it after large code changes. */\n"
                  "SECTIONS\n{\n  .text.hot_cordinal : ALIGN(4096)\n  {\n")
        for name in hot:
            out.write(f"    *(.text.{name})\n")
        out.write("  }\n}\nINSERT BEFORE .text;\n")
    print(f"{len(hot)} functions on {len(pages)} pages")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "pages" and len(sys.argv) == 5:
        with open(sys.argv[4], "a") as f:
            for page in resident(sys.argv[2], sys.argv[3]):
                f.write(f"{page}\n")
    elif command == "write" and len(sys.argv) == 5:
        write(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        sys.exit(__doc__)
